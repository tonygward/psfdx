// Issue as prompt. A Doing or Todo card whose issue has enough detail does not need a prompt file first: Matrix builds a
// canonical prompt from the issue, saves it in the same pull request, and carries on. An issue without enough detail gets
// one comment saying what is missing, and its card moves to Blocked. Nothing here starts the agent or writes to the
// repository. Only issues the repository owner wrote are used, and issue comments are never read as instructions.
import { parsePrompt, digest } from './backlog.mjs';
import { ownerIssue } from './board.mjs';
import { commentMarker } from './github-io.mjs';

export const REQUIRED = [
  ['objective', /objective|goal|purpose|summary|user value|problem|background/i, 'an objective (what this changes and why it matters)'],
  ['scope', /implementation|scope|requirements?|approach|desired|existing|changes|behaviou?r/i, 'scope or implementation notes (what to change, and where)'],
  ['acceptance', /accept|done when|definition of done|success criteria/i, 'acceptance criteria (how we know it is finished)'],
  ['tests', /\btests?\b|testing|verification|validat/i, 'tests (what proves it works)'],
];
// Issue text never holds a card: wording such as "deferred" or "not queued" is ignored. Only the board column does.
const MIN_CHARS = 30;

/** Splits an issue body into { heading, text } sections. Headings are Markdown headings or a line that is only a bold label. */
export function sections(body) {
  const out = [], lines = String(body ?? '').replace(/\r\n/g, '\n').split('\n');
  let current = { heading: '', text: '' };
  for (const line of lines) {
    const heading = /^#{1,6}\s+(.*\S)\s*$/.exec(line)?.[1] ?? /^\*\*([^*\n]{2,80}?):?\*\*:?\s*$/.exec(line)?.[1];
    if (heading) { out.push(current); current = { heading, text: '' }; } else current.text += line + '\n';
  }
  out.push(current);
  return out;
}

/** { ok, missing[] }: what an issue still lacks before Matrix may build from it. */
export function assessIssue(body) {
  const parts = sections(body), substantial = part => part.text.replace(/\s+/g, '').length >= MIN_CHARS;
  const missing = [];
  for (const [key, pattern, label] of REQUIRED) {
    const found = parts.some(part => part.heading && pattern.test(part.heading) && substantial(part));
    // A combined heading ("Acceptance criteria and tests") or an acceptance section that names its tests also covers the tests.
    const testsInAcceptance = key === 'tests' && parts.some(part => /accept/i.test(part.heading) && substantial(part) && /\btests?\b|verif|validat/i.test(part.text));
    if (!found && !testsInAcceptance) missing.push(label);
  }
  return { ok: missing.length === 0, missing };
}

const slug = (title, id) => title.replace(new RegExp(`^${id}\\s*[—–:-]\\s*`, 'i'), '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60) || 'task';

/** Canonical prompt path for a task ID and issue title: one flat folder, prompts/<ID>-<slug>.md. */
export const promptPath = (id, title, directory = 'prompts') => `${directory}/${id}-${slug(title, id)}.md`;

/** Builds and validates the canonical prompt for a card from its issue. Returns the parsed prompt with { generated: { file, text } }. */
export function promptFromIssue(card, body, { issueUrl, prefixes } = {}) {
  const file = promptPath(card.taskId, card.title ?? '');
  const title = (card.title ?? card.taskId).trim();
  // No status, execution or model: the board owns status and Matrix always runs Sonnet.
  const text = ['---', `id: ${card.taskId}`, 'priority: medium', 'effort: medium', 'dependencies: []', 'conflicts: []', '---', '',
    `# ${title}`, '',
    `**Tracking issue:** ${issueUrl ?? `#${card.issue}`}`, '',
    'Generated by Matrix from the tracking issue when the card was picked up, because no prompt file existed and the issue had enough detail. The issue text below is the specification.', '',
    String(body).replace(/\r\n/g, '\n').trim(), ''].join('\n');
  const prompt = parsePrompt(file, text, prefixes);
  return { ...prompt, generated: { file, text } };
}

export const needsDetailMarker = (id, hash) => commentMarker('needs-detail', id, hash);
export const notOwnerMarker = (id, issue) => commentMarker('not-owner', id, String(issue));

export function needsDetailComment(id, missing, hash) {
  return [needsDetailMarker(id, hash), `**${id} is Blocked: the issue does not have enough detail to build from.**`, '',
    'There is no prompt file for this task, and Matrix can only build from the issue when it has all of these. Still missing:', '',
    ...missing.map(item => `- ${item}`), '',
    '**To resume:** add the missing detail to the issue (or add a prompt file under `prompts/`), then move this card back to Todo or Doing. Matrix will not retry on its own.'].join('\n');
}

export function notOwnerComment(id, issue) {
  return [notOwnerMarker(id, issue), `**${id} is Blocked: Matrix only builds from issues written by the repository owner.**`, '',
    'This repository is public. Matrix never builds from an issue someone else wrote, and never reads issue comments as instructions.', '',
    '**To resume:** the owner can open a new issue with the details, then add it to the board.'].join('\n');
}

/**
 * For Doing/Todo cards with no prompt file: assess the issue. Sufficient issues yield a generated prompt; insufficient ones are
 * commented on once (deduplicated by a marker that includes the issue text) and the card moves to Blocked.
 * io: { issueBody(repository, issue), hasComment, comment, moveToBlocked }
 * Returns { prompts: generated prompts, blocked: ids, notes: [] }. In a dry run nothing is written.
 */
export async function resolveFromIssues({ board, prompts, tasks = {}, io, statuses, repository, ownerLogin = null, prefixes, dryRun = true, merged = new Set(), open = new Set() }) {
  const known = new Set(prompts.map(p => p.id)), generated = [], blocked = [], notes = [];
  for (const card of board.cards) {
    if (!statuses.includes(card.status) || !card.issue || card.state !== 'OPEN' || !card.taskId || known.has(card.taskId)) continue;
    // A task resumed with committed work has an open pull request by design; its prompt is rebuilt from the issue so the resume can be selected.
    if (merged.has(card.taskId) || (open.has(card.taskId) && !tasks[card.taskId]?.resumeWork)) continue;
    if (tasks[card.taskId] && !['pending', 'withdrawn'].includes(tasks[card.taskId].state)) continue;
    try {
      if (!ownerIssue(card, repository, ownerLogin)) {
        notes.push(`${card.taskId}: not written by the repository owner`);
        if (dryRun) continue;
        if (!(await io.hasComment(card.repository, card.issue, notOwnerMarker(card.taskId, card.issue)))) await io.comment(card.repository, card.issue, notOwnerComment(card.taskId, card.issue));
        await io.moveToBlocked(card.itemId); card.status = 'Blocked'; blocked.push(card.taskId);
        continue;
      }
      const body = await io.issueBody(card.repository, card.issue), verdict = assessIssue(body);
      let missing = verdict.missing, prompt = null;
      if (verdict.ok) {
        try { prompt = promptFromIssue(card, body, { issueUrl: `https://github.com/${card.repository}/issues/${card.issue}`, prefixes }); }
        catch (error) { missing = [`a prompt Matrix can read (${error.message})`]; }
      }
      if (prompt) { generated.push(prompt); notes.push(`${card.taskId}: built from the issue`); continue; }
      notes.push(`${card.taskId}: not enough detail (${missing.length} missing)`);
      if (dryRun) continue;
      // The marker holds a hash of the missing list and the issue text, so the comment is repeated only when the issue changes.
      const hash = digest(`${missing.join('|')}\n${body}`).slice(0, 12);
      if (!(await io.hasComment(card.repository, card.issue, needsDetailMarker(card.taskId, hash)))) await io.comment(card.repository, card.issue, needsDetailComment(card.taskId, missing, hash));
      await io.moveToBlocked(card.itemId); card.status = 'Blocked'; blocked.push(card.taskId);
    } catch (error) { notes.push(`${card.taskId}: could not assess (${String(error.message).slice(0, 120)})`); }
  }
  return { prompts: generated, blocked, notes };
}
